def resolve_executable(value: str, label: str) -> str:
    expanded = os.path.expanduser(value)
    if os.path.sep in expanded:
        path = Path(expanded).resolve()
        if not path.is_file() or not os.access(path, os.X_OK):
            raise ScriptError(f"{label} is not executable: {value}")
        return str(path)
    resolved = shutil.which(expanded)
    if not resolved:
        raise ScriptError(f"{label} executable was not found in PATH: {value}")
    return resolved


def find_source_video(processing_dir: Path) -> Path:
    """Find and validate the single source_link.<extension> symlink in the project root."""
    try:
        candidates = sorted(
            path for path in processing_dir.glob("source_link.*")
            if path.name.startswith("source_link.") and path.name[len("source_link."):]
        )
    except OSError as exc:
        raise ScriptError(f"Could not search for the source video link in '{processing_dir}': {exc}") from exc

    if not candidates:
        raise ScriptError(
            f"Required source symlink not found in project folder: {processing_dir}. "
            "Expected exactly one file named 'source_link' with a video extension, such as "
            "source_link.ts, source_link.mp4, or source_link.mkv."
        )
    if len(candidates) > 1:
        names = ", ".join(path.name for path in candidates)
        raise ScriptError(
            f"Found multiple files matching 'source_link.*' in '{processing_dir}': {names}. "
            "Keep exactly one source_link file."
        )

    source_link = candidates[0]
    if not source_link.is_symlink():
        raise ScriptError(
            f"The source file must be a symbolic link, but this is not a symlink: {source_link}"
        )

    try:
        resolved_target = source_link.resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        raise ScriptError(
            f"Source symlink is broken or its target cannot be resolved: {source_link}: {exc}"
        ) from exc
    if not resolved_target.is_file():
        try:
            link_target = os.readlink(source_link)
        except OSError:
            link_target = "<target unavailable>"
        raise ScriptError(
            f"Source symlink does not point to a regular file: {source_link} -> {link_target}"
        )
    return source_link


def parse_filename_timestamp(value: str) -> tuple[int, float, str]:
    """Parse HH-MM-SS-mmm into exact milliseconds, seconds, and display text."""
    match = re.fullmatch(r"(\d{2,})-(\d{2})-(\d{2})-(\d{3})", value)
    if match is None:
        raise ValueError("timestamp must use HH-MM-SS-mmm")
    hours, minutes, seconds, milliseconds = (int(part) for part in match.groups())
    if minutes >= 60 or seconds >= 60:
        raise ValueError("minutes and seconds must be below 60")
    total_ms = (((hours * 60) + minutes) * 60 + seconds) * 1000 + milliseconds
    total_seconds = total_ms / 1000.0
    display = f"{hours:02d}:{minutes:02d}:{seconds:02d}.{milliseconds:03d}"
    return total_ms, total_seconds, display


def format_filename_timestamp(total_ms: int) -> str:
    """Format milliseconds as HH-MM-SS-mmm for segment filenames."""
    if total_ms < 0:
        raise ValueError("Cannot format a negative timestamp.")
    hours, remainder = divmod(total_ms, 3_600_000)
    minutes, remainder = divmod(remainder, 60_000)
    seconds, milliseconds = divmod(remainder, 1000)
    return f"{hours:02d}-{minutes:02d}-{seconds:02d}-{milliseconds:03d}"


def segment_output_filename(segment: Segment) -> str:
    """Build the MP4 filename from the original source-time range."""
    start = format_filename_timestamp(segment.start_milliseconds)
    end = format_filename_timestamp(segment.end_milliseconds)
    return f"{start} - {end}.mp4"


def parse_encoded_segment_range(path: Path) -> tuple[int, int, str, str]:
    """Read the original source-time range from an encoded segment filename."""
    match = SEGMENT_FILENAME_RE.fullmatch(path.stem)
    if match is None:
        raise ScriptError(
            f"Invalid encoded segment filename: '{path.name}'. "
            "Expected 'HH-MM-SS-mmm - HH-MM-SS-mmm.mp4'."
        )
    try:
        start_ms, _start_seconds, start_text = parse_filename_timestamp(match.group("start"))
        end_ms, _end_seconds, end_text = parse_filename_timestamp(match.group("end"))
    except ValueError as exc:
        raise ScriptError(f"Invalid timestamp in encoded segment filename '{path.name}': {exc}") from exc
    if end_ms <= start_ms:
        raise ScriptError(
            f"Encoded segment end must be later than its start: '{path.name}'."
        )
    return start_ms, end_ms, start_text, end_text


def sort_and_validate_encoded_segments(
    output_dir: Path, expected_segments: list[Segment] | None
) -> list[Path]:
    """Sort encoded files by filename timestamps, reject overlaps, and optionally check expected files."""
    expected_names = (
        {segment_output_filename(segment) for segment in expected_segments}
        if expected_segments is not None else None
    )
    try:
        actual_paths = sorted(
            path for path in output_dir.iterdir()
            if path.is_file() and path.suffix.lower() == ".mp4"
        )
    except OSError as exc:
        raise ScriptError(f"Could not list encoded segment folder '{output_dir}': {exc}") from exc

    if not actual_paths:
        raise ScriptError(f"No encoded MP4 segments were found in: {output_dir}")

    parsed_paths: list[tuple[int, int, str, str, Path]] = []
    for path in actual_paths:
        start_ms, end_ms, start_text, end_text = parse_encoded_segment_range(path)
        parsed_paths.append((start_ms, end_ms, start_text, end_text, path))
    parsed_paths.sort(key=lambda item: (item[0], item[1], item[4].name))

    for previous, current in zip(parsed_paths, parsed_paths[1:]):
        previous_start, previous_end, previous_start_text, previous_end_text, previous_path = previous
        current_start, current_end, current_start_text, current_end_text, current_path = current
        if current_start < previous_end:
            raise ScriptError(
                "Encoded segment time ranges overlap: "
                f"'{previous_path.name}' ({previous_start_text} - {previous_end_text}) and "
                f"'{current_path.name}' ({current_start_text} - {current_end_text}). "
                "The segments cannot be muxed safely. Remove or correct the overlapping segment files."
            )

    actual_names = {path.name for _start, _end, _start_text, _end_text, path in parsed_paths}
    if expected_names is not None:
        unexpected_names = sorted(actual_names - expected_names)
        if unexpected_names:
            listed = ", ".join(f"'{name}'" for name in unexpected_names[:8])
            if len(unexpected_names) > 8:
                listed += f", and {len(unexpected_names) - 8} more"
            raise ScriptError(
                "Unexpected encoded segment file(s) were found that do not match the current "
                f"validated scenes: {listed}. These may be left over from an earlier run. "
                "Move or remove them before muxing."
            )

        missing_names = sorted(expected_names - actual_names)
        if missing_names:
            listed = ", ".join(f"'{name}'" for name in missing_names[:8])
            if len(missing_names) > 8:
                listed += f", and {len(missing_names) - 8} more"
            raise ScriptError(f"Cannot mux: expected encoded segment file(s) are missing: {listed}.")

    return [path for _start, _end, _start_text, _end_text, path in parsed_paths]


def load_segments(scenes_dir: Path) -> tuple[list[Segment], int]:
    """Load scene ranges from image filenames and merge exactly adjacent ranges."""
    if not scenes_dir.is_dir():
        raise ScriptError(f"Validated scenes folder not found: {scenes_dir}")

    try:
        image_paths = [
            path for path in scenes_dir.iterdir()
            if path.is_file() and path.suffix.lower() in IMAGE_EXTENSIONS
        ]
    except OSError as exc:
        raise ScriptError(f"Could not list validated scenes folder '{scenes_dir}': {exc}") from exc

    if not image_paths:
        raise ScriptError(f"No .jpg or .jpeg segment images were found in: {scenes_dir}")

    parsed: list[Segment] = []
    for image_path in image_paths:
        match = SEGMENT_FILENAME_RE.fullmatch(image_path.stem)
        if match is None:
            raise ScriptError(
                f"Invalid validated-scene filename: '{image_path.name}'. "
                "Expected 'HH-MM-SS-mmm - HH-MM-SS-mmm.jpg'."
            )
        try:
            start_ms, start_seconds, start_text = parse_filename_timestamp(match.group("start"))
            end_ms, end_seconds, end_text = parse_filename_timestamp(match.group("end"))
        except ValueError as exc:
            raise ScriptError(f"Invalid timestamp in validated-scene filename '{image_path.name}': {exc}") from exc
        if end_ms <= start_ms:
            raise ScriptError(
                f"Segment end must be later than its start in validated-scene filename: '{image_path.name}'"
            )
        parsed.append(
            Segment(
                start_text=start_text,
                end_text=end_text,
                start_seconds=start_seconds,
                end_seconds=end_seconds,
                start_milliseconds=start_ms,
                end_milliseconds=end_ms,
            )
        )

    parsed.sort(key=lambda item: (item.start_milliseconds, item.end_milliseconds))
    merged: list[Segment] = []
    for current in parsed:
        if merged and current.start_milliseconds < merged[-1].end_milliseconds:
            previous = merged[-1]
            raise ScriptError(
                "Validated scene ranges overlap: "
                f"{previous.start_text} - {previous.end_text} and "
                f"{current.start_text} - {current.end_text}. "
                "Check the scene image filenames before encoding."
            )
        if merged and current.start_milliseconds == merged[-1].end_milliseconds:
            previous = merged[-1]
            merged[-1] = Segment(
                start_text=previous.start_text,
                end_text=current.end_text,
                start_seconds=previous.start_seconds,
                end_seconds=current.end_seconds,
                start_milliseconds=previous.start_milliseconds,
                end_milliseconds=current.end_milliseconds,
                source_count=previous.source_count + current.source_count,
            )
        else:
            merged.append(current)

    return merged, len(parsed)


def run_command(command: Sequence[str], *, capture: bool = True) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            list(command), check=False, text=True, encoding="utf-8", errors="replace",
            stdout=subprocess.PIPE if capture else None,
            stderr=subprocess.PIPE if capture else None,
        )
    except FileNotFoundError as exc:
        raise ScriptError(f"Executable was not found: {command[0]}") from exc
    except OSError as exc:
        raise ScriptError(f"Could not run '{command[0]}': {exc}") from exc


def probe_container_start(ffprobe: str, source_video: Path) -> float:
    command = [
        ffprobe, "-v", "error", "-show_entries", "format=start_time",
        "-of", "default=noprint_wrappers=1:nokey=1", str(source_video),
    ]
    result = run_command(command)
    if result.returncode != 0:
        details = (result.stderr or result.stdout or "").strip()
        raise ScriptError(f"Could not read container start_time from the source video. {details}".rstrip())
    value = (result.stdout or "").strip().splitlines()
    if not value:
        raise ScriptError("Could not read a valid container start_time from the source video.")
    try:
        start = float(value[0])
    except ValueError as exc:
        raise ScriptError("Could not read a valid container start_time from the source video.") from exc
    if not math.isfinite(start):
        raise ScriptError("Could not read a valid container start_time from the source video.")
    return start


def parse_frame_rate(value: object) -> Fraction | None:
    """Parse an FFprobe rate such as 24000/1001, rejecting unknown rates."""
    if not isinstance(value, str) or not value.strip():
        return None
    try:
        rate = Fraction(value.strip())
    except (ValueError, ZeroDivisionError):
        return None
    return rate if rate > 0 else None


def detect_bit_depth(pixel_format: str, bits_per_raw_sample: object) -> int:
    """Infer component bit depth from FFprobe metadata, defaulting conservatively to 8-bit."""
    bit_depth = 8
    try:
        raw_depth = int(bits_per_raw_sample)
        if raw_depth > bit_depth:
            bit_depth = raw_depth
    except (TypeError, ValueError):
        pass

    value = pixel_format.strip().lower()
    # Covers common planar formats (yuv420p10le, gbrp12le), packed formats (p010le),
    # and grayscale formats (gray10le). RGB48/RGBA64 represent 16-bit components.
    match = re.search(r"p0?(9|10|12|14|16)(?:le|be)?$", value)
    if match:
        bit_depth = max(bit_depth, int(match.group(1)))
    else:
        match = re.search(r"(?:gray|ya|rgb|rgba|bgra|argb|abgr|gbr|xyz)(9|10|12|14|16)(?:le|be)?$", value)
        if match:
            bit_depth = max(bit_depth, int(match.group(1)))
        elif re.search(r"(?:rgb|bgr|rgba|bgra|argb|abgr)(?:48|64)(?:le|be)?$", value):
            bit_depth = max(bit_depth, 16)
    return bit_depth


def probe_video_properties(ffprobe: str, source_video: Path) -> VideoProperties:
    command = [
        ffprobe, "-v", "error", "-select_streams", "v:0",
        "-show_entries", "stream=codec_name,avg_frame_rate,r_frame_rate,field_order,pix_fmt,bits_per_raw_sample",
        "-of", "json", str(source_video),
    ]
    result = run_command(command)
    if result.returncode != 0:
        details = (result.stderr or result.stdout or "").strip()
        raise ScriptError(f"Could not inspect the source video with ffprobe. {details}".rstrip())
    try:
        streams = json.loads(result.stdout or "{}").get("streams", [])
    except json.JSONDecodeError as exc:
        raise ScriptError("FFprobe returned invalid JSON while inspecting the source video.") from exc
    if not streams:
        raise ScriptError("FFprobe did not report a video stream for the source file.")

    stream = streams[0]
    codec = str(stream.get("codec_name") or "").strip().lower()
    if not codec:
        raise ScriptError("FFprobe did not report a video codec for the source file.")

    # Prefer the measured average rate, falling back to the nominal/base rate when
    # average rate is unavailable (common for some transport streams).
    frame_rate = parse_frame_rate(stream.get("avg_frame_rate"))
    if frame_rate is None:
        frame_rate = parse_frame_rate(stream.get("r_frame_rate"))
    if frame_rate is None:
        raise ScriptError(
            "Could not determine a valid input frame rate from ffprobe "
            f"(avg_frame_rate={stream.get('avg_frame_rate')!r}, "
            f"r_frame_rate={stream.get('r_frame_rate')!r})."
        )

    field_order = str(stream.get("field_order") or "unknown").strip().lower()
    pixel_format = str(stream.get("pix_fmt") or "unknown").strip().lower()
    bit_depth = detect_bit_depth(pixel_format, stream.get("bits_per_raw_sample"))
    return VideoProperties(
        codec=codec,
        frame_rate=frame_rate,
        field_order=field_order,
        pixel_format=pixel_format,
        bit_depth=bit_depth,
    )


def probe_frame_interlace_flags(ffprobe: str, source_video: Path) -> tuple[int, int, int]:
    """Return (interlaced, progressive, total) counts from decoded-frame flags."""
    command = [
        ffprobe, "-v", "error", "-select_streams", "v:0",
        "-read_intervals", "%+12", "-show_frames",
        "-show_entries", "frame=interlaced_frame,top_field_first",
        "-of", "json", str(source_video),
    ]
    result = run_command(command)
    if result.returncode != 0:
        return 0, 0, 0
    try:
        frames = json.loads(result.stdout or "{}").get("frames", [])
    except json.JSONDecodeError:
        return 0, 0, 0

    interlaced = 0
    progressive = 0
    for frame in frames:
        value = frame.get("interlaced_frame")
        try:
            flag = int(value)
        except (TypeError, ValueError):
            continue
        if flag == 1:
            interlaced += 1
        elif flag == 0:
            progressive += 1
    return interlaced, progressive, interlaced + progressive


def detect_interlaced(
    ffmpeg: str,
    ffprobe: str,
    source_video: Path,
    field_order: str,
) -> tuple[bool, str]:
    """Run content-based detection first, then use decoded-frame flags or metadata as fallbacks."""
    # Explicit --scan-type detect means the user has accepted the slower content scan.
    # Run idet even when container metadata claims a scan type, because the metadata may
    # be missing or stale. idet can be inconclusive for some valid progressive encodes.
    command = [
        ffmpeg, "-hide_banner", "-nostdin", "-loglevel", "info",
        "-i", str(source_video), "-map", "0:v:0", "-vf", "idet",
        "-frames:v", "300", "-an", "-sn", "-dn", "-f", "null", "-",
    ]
    result = run_command(command)
    log = (result.stderr or "") + "\n" + (result.stdout or "")
    match = re.search(
        r"Multi frame detection:\s*TFF:\s*(\d+)\s+BFF:\s*(\d+)\s+"
        r"Progressive:\s*(\d+)\s+Undetermined:\s*(\d+)",
        log,
        re.IGNORECASE,
    )
    tff = bff = progressive = undetermined = 0
    if match is not None:
        tff, bff, progressive, undetermined = (int(value) for value in match.groups())
        interlaced_votes = tff + bff
        if interlaced_votes > progressive:
            return True, f"FFmpeg idet (TFF={tff}, BFF={bff}, progressive={progressive})"
        if progressive > interlaced_votes:
            return False, f"FFmpeg idet (TFF={tff}, BFF={bff}, progressive={progressive})"

    # If idet has no clear winner, check the decoded-frame flags reported by ffprobe.
    # This catches sources where field_order is unknown and idet marks every frame as
    # Undetermined rather than Progressive. Require a useful sample and a strong majority.
    frame_interlaced, frame_progressive, frame_total = probe_frame_interlace_flags(
        ffprobe, source_video
    )
    if frame_total >= 10:
        if frame_interlaced >= 0.8 * frame_total:
            return True, (
                f"ffprobe decoded-frame flags (interlaced={frame_interlaced}, "
                f"progressive={frame_progressive})"
            )
        if frame_progressive >= 0.8 * frame_total:
            return False, (
                f"ffprobe decoded-frame flags (interlaced={frame_interlaced}, "
                f"progressive={frame_progressive})"
            )

    idet_details = (
        f"TFF={tff}, BFF={bff}, progressive={progressive}, undetermined={undetermined}"
        if match is not None else "no usable idet frame statistics"
    )
    frame_details = (
        f"interlaced={frame_interlaced}, progressive={frame_progressive}, total={frame_total}"
    )
    # If image-based methods cannot decide, a recognized field_order is still a useful
    # last-resort signal. This fallback is only used in explicit --scan-type detect mode.
    if field_order == "progressive":
        return False, "ffprobe field_order=progressive (fallback after inconclusive content detection)"
    if field_order in {"tt", "bb", "tb", "bt"}:
        return True, f"ffprobe field_order={field_order} (fallback after inconclusive content detection)"

    detail_lines = []
    if result.returncode != 0:
        ffmpeg_details = log.strip().splitlines()[-5:]
        if ffmpeg_details:
            detail_lines.append("FFmpeg idet output:\n" + "\n".join(ffmpeg_details))
    extra = "\n" + "\n".join(detail_lines) if detail_lines else ""
    raise ScriptError(
        "Content-based scan-type detection was inconclusive: "
        f"ffprobe field_order={field_order}; FFmpeg idet reported {idet_details}; "
        f"decoded-frame flags reported {frame_details}. "
        "Specify --scan-type progressive or --scan-type interlaced if you know the source type."
        + extra
    )


def format_frame_rate(rate: Fraction) -> str:
    decimal = f"{float(rate):.6f}".rstrip("0").rstrip(".")
    if rate.denominator == 1:
        return f"{decimal} fps"
    return f"{decimal} fps ({rate.numerator}/{rate.denominator})"


def ffmpeg_rate_value(rate: Fraction) -> str:
    """Return an exact rate string accepted by FFmpeg options and expressions."""
    return str(rate.numerator) if rate.denominator == 1 else f"{rate.numerator}/{rate.denominator}"


def make_encode_command(
    *,
    ffmpeg: str,
    source_video: Path,
    output_path: Path,
    segment: Segment,
    container_start: float,
    applied_offset: float,
    edge_trim: float,
    seek_back: float,
    qp: int,
    tier: str,
    level: str,
    hardware_decode: bool,
    convert_to_8bit: bool,
    interlaced: bool,
    source_frame_rate: Fraction,
    force_overwrite: bool,
) -> tuple[list[str], float, float, float]:
    effective_start = segment.start_seconds + applied_offset
    effective_end = segment.end_seconds + applied_offset
    if effective_start < 0 or effective_end <= effective_start:
        raise ScriptError(
            f"Custom offset makes segment invalid: start={effective_start:.6f} end={effective_end:.6f}"
        )

    # FFmpeg -copyts preserves the input timestamp domain. Add the container's start
    # offset to player-relative segment times and shorten both boundaries by edge_trim.
    trim_start = effective_start + container_start + edge_trim
    trim_end = effective_end + container_start - edge_trim
    if trim_end <= trim_start:
        raise ScriptError(
            f"Segment is too short after boundary trimming: {segment.start_text} - {segment.end_text}"
        )
    seek_time = max(0.0, effective_start - seek_back)
    trim_filter = f"trim=start={trim_start:.6f}:end={trim_end:.6f}"
    audio_filter = f"atrim=start={trim_start:.6f}:end={trim_end:.6f},asetpts=PTS-STARTPTS"
    output_frame_rate = source_frame_rate * 2 if interlaced else None

    if interlaced:
        # Interlaced hardware decoding uses Rockchip IEP; software decoding uses
        # bwdif send_field. Both paths create two progressive frames per source frame.
        rate_value = ffmpeg_rate_value(output_frame_rate)
        pts_filter = f"setpts=N/(({rate_value})*TB)"
        if not hardware_decode:
            video_filter = (
                f"format=yuv420p,bwdif=mode=send_field:parity=auto:deint=all,"
                f"{trim_filter},{pts_filter}"
            )
        else:
            video_filter = f"{trim_filter},{pts_filter}"
            if convert_to_8bit:
                video_filter = (
                    "scale_rkrga=format=nv12:force_yuv=8bit:force_chroma=420sp,"
                    f"{video_filter}"
                )
    else:
        # Preserve input frame timestamps for progressive sources. Do not force a fixed
        # output rate: this also preserves variable-frame-rate sources and prevents speed-up.
        video_filter = f"{trim_filter},setpts=PTS-STARTPTS"
        if hardware_decode and convert_to_8bit:
            video_filter = (
                "scale_rkrga=format=nv12:force_yuv=8bit:force_chroma=420sp,"
                f"{video_filter}"
            )
        elif not hardware_decode:
            # Software decoding converts higher bit depths and non-4:2:0 inputs to 8-bit 4:2:0.
            video_filter = f"format=yuv420p,{video_filter}"

    command = [ffmpeg, "-hide_banner", "-loglevel", "error", "-nostats", "-copyts"]
    if hardware_decode:
        # In ffmpeg-rockchip, -hwaccel rkmpp selects the appropriate MPP decoder automatically.
        # The decoder's default IEP deinterlacing behavior is retained for interlaced sources.
        command += ["-hwaccel", "rkmpp", "-hwaccel_output_format", "drm_prime"]
    command += ["-ss", f"{seek_time:.3f}", "-i", str(source_video)]
    overwrite = "-y" if force_overwrite else "-n"
    command += ["-map", "0:v:0", "-filter:v", video_filter, "-c:v", "hevc_rkmpp"]
    if interlaced:
        # Keep the output at twice the nominal source frame rate after deinterlacing.
        command += ["-r:v", ffmpeg_rate_value(output_frame_rate), "-fps_mode:v", "cfr"]
    else:
        # Keep the source cadence (including non-integer and variable frame rates).
        command += ["-fps_mode:v", "passthrough"]
    command += [
        "-rc_mode", "CQP", "-qp_init", str(qp), "-qp_min", str(qp), "-qp_max", str(qp),
        "-qp_min_i", str(qp), "-qp_max_i", str(qp), "-tier", tier, "-level", level,
        "-map", "0:a:0", "-filter:a", audio_filter, "-c:a", "aac", "-b:a", "256k",
        overwrite, str(output_path),
    ]
    return command, trim_start, trim_end, seek_time


def clean_partial_output(output_path: Path) -> None:
    try:
        output_path.unlink(missing_ok=True)
    except OSError:
        pass


def mux_encoded_segments(
    ffmpeg: str,
    processing_dir: Path,
    output_dir: Path,
    complete_output: Path,
    mux_segments: list[Path],
) -> None:
    """Mux timestamp-named MP4 segments into the final MKV atomically."""
    concat_list_path: Path | None = None
    mux_temp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", prefix=".concat_list.", suffix=".txt", dir=output_dir,
            encoding="utf-8", delete=False,
        ) as concat_file:
            concat_list_path = Path(concat_file.name)
            for path in mux_segments:
                # Filenames are constrained to numeric timestamps and a fixed separator.
                concat_file.write(f"file '{path.name}'\n")

        fd, temp_name = tempfile.mkstemp(
            prefix=".output_video.", suffix=".mkv", dir=processing_dir
        )
        os.close(fd)
        mux_temp_path = Path(temp_name)
        print("\n[Mux] Muxing encoded segments in chronological order...")
        mux_command = [
            ffmpeg, "-hide_banner", "-loglevel", "error", "-nostats",
            "-f", "concat", "-safe", "0", "-i", concat_list_path.name,
            "-c", "copy", "-y", str(mux_temp_path),
        ]
        try:
            result = subprocess.run(mux_command, cwd=str(output_dir), check=False)
        except OSError as exc:
            raise ScriptError(f"Could not run FFmpeg while muxing encoded segments: {exc}") from exc
        if result.returncode != 0:
            raise ScriptError(
                f"FFmpeg failed while muxing encoded segments, exit code {result.returncode}. "
                "Existing output_video.mkv was preserved."
            )
        try:
            os.chmod(mux_temp_path, 0o664)
            os.replace(mux_temp_path, complete_output)
        except OSError as exc:
            raise ScriptError(f"Could not finalize mux output '{complete_output}': {exc}") from exc
        mux_temp_path = None
        print("[Mux] The segments were successfully muxed and saved to: output_video.mkv")
        print()
    finally:
        if concat_list_path is not None:
            concat_list_path.unlink(missing_ok=True)
        if mux_temp_path is not None:
            mux_temp_path.unlink(missing_ok=True)


def main() -> int:
    started = time.monotonic()
    parser = build_parser()
    args = parser.parse_args()

    try:
        if not math.isfinite(args.edge_trim) or args.edge_trim < 0:
            raise ScriptError("--edge-trim must be a finite non-negative number.")
        if not math.isfinite(args.seek_back) or args.seek_back < 0:
            raise ScriptError("--seek-back must be a finite non-negative number.")
        if not math.isfinite(args.custom_offset):
            raise ScriptError("--custom-offset must be a finite signed number of seconds.")

        processing_dir = args.processing_folder.expanduser().resolve()
        if not processing_dir.is_dir():
            raise ScriptError(f"Processing folder not found: {args.processing_folder}")
        output_dir = processing_dir / "encoded_seg"
        complete_output = processing_dir / "output_video.mkv"
        if complete_output.exists() and not complete_output.is_file():
            raise ScriptError(f"Mux output path exists but is not a regular file: {complete_output}")

        ffmpeg = resolve_executable(args.ffmpeg, "FFmpeg")

        # Mux-only mode deliberately does not inspect source_link or scenes_validated.
        # It uses every timestamp-named MP4 already present in encoded_seg.
        if args.just_mux:
            mux_segments = sort_and_validate_encoded_segments(output_dir, None)
            print("Mux-only mode:")
            print(f" - encoded folder: {output_dir}")
            print(f" - existing segments: {len(mux_segments)} (chronological order)")
            print(f" - output file: {complete_output}")
            if args.skip_mux:
                print(" - note: --just-mux overrides --skip-mux")
            mux_encoded_segments(
                ffmpeg, processing_dir, output_dir, complete_output, mux_segments
            )
            print(f"Total runtime: {format_runtime(started)} (hh:mm:ss)")
            return 0

        if args.qp is None or args.tier is None or args.level is None:
            raise ScriptError("Encoding requires --qp, --tier and --level unless --just-mux is specified.")
        if args.qp < 0:
            raise ScriptError("--qp must be a non-negative integer.")

        source_video = find_source_video(processing_dir)
        scenes_dir = processing_dir / "scenes_validated"
        ffprobe = resolve_executable(args.ffprobe, "FFprobe")
        segments, listed_segment_count = load_segments(scenes_dir)
        container_start = probe_container_start(ffprobe, source_video)
        video_properties = probe_video_properties(ffprobe, source_video)
        source_codec = video_properties.codec
        source_frame_rate = video_properties.frame_rate
        # Let ffmpeg-rockchip choose the specific MPP decoder from the input codec.
        # In auto mode a failed hardware attempt is retried with software decoding.
        initial_hardware_decode = args.decode_mode != "software"
        if args.scan_type == "auto":
            # Fast mode: trust only explicit stream metadata. Do not run idet or scan frames.
            field_order = video_properties.field_order
            if field_order == "progressive":
                is_interlaced = False
                scan_detection_method = "ffprobe field_order=progressive"
            elif field_order in {"tt", "bb", "tb", "bt"}:
                is_interlaced = True
                scan_detection_method = f"ffprobe field_order={field_order}"
            else:
                raise ScriptError(
                    "Cannot determine the source scan type from ffprobe metadata "
                    f"(field_order={field_order}). Automatic mode does not inspect frame content. "
                    "Use --scan-type detect to run slower FFmpeg idet detection, or specify "
                    "--scan-type progressive or --scan-type interlaced if you know the source type."
                )
        elif args.scan_type == "detect":
            is_interlaced, scan_detection_method = detect_interlaced(
                ffmpeg, ffprobe, source_video, video_properties.field_order
            )
        else:
            is_interlaced = args.scan_type == "interlaced"
            scan_detection_method = f"command-line override (--scan-type {args.scan_type})"
        output_frame_rate = source_frame_rate * 2 if is_interlaced else None

        output_dir.mkdir(parents=True, exist_ok=True)
        segment_count = len(segments)
        expected_output_names = [segment_output_filename(segment) for segment in segments]
        if len(set(expected_output_names)) != len(expected_output_names):
            raise ScriptError(
                "Two or more validated ranges produce the same encoded filename. "
                "Check the timestamp ranges in scenes_validated."
            )
        for output_name in expected_output_names:
            output_path = output_dir / output_name
            if output_path.exists() and not output_path.is_file():
                raise ScriptError(f"Output path exists but is not a regular file: {output_path}")
        print("Input:")
        try:
            source_link_target = os.readlink(source_video)
        except OSError:
            source_link_target = "<target unavailable>"
        print(f" - source file: {source_video} -> {source_link_target}")
        print(f" - container start_time: {container_start:.6f}")
        print(f" - segments listed: {listed_segment_count}")
        print(f" - video codec: {source_codec}")
        if args.decode_mode == "auto":
            decoding_description = "automatic Rockchip MPP decoder selection (software fallback enabled)"
        elif args.decode_mode == "hardware":
            decoding_description = "automatic Rockchip MPP decoder selection (software fallback disabled)"
        else:
            decoding_description = "software (requested by --decode-mode software)"
        print(f" - video decoding: {decoding_description}")
        print(f" - frame rate: {format_frame_rate(source_frame_rate)}")
        scan_label = "interlaced" if is_interlaced else "progressive"
        print(f" - scan type: {scan_label} ({scan_detection_method})")
        print(f" - pixel format: {video_properties.pixel_format} ({video_properties.bit_depth}-bit)")
        print()
        print("Output:")
        print(f" - boundary trim: {args.edge_trim:g} s at each end")
        if is_interlaced:
            output_rate_description = (
                f"{format_frame_rate(output_frame_rate)} "
                "(deinterlaced; double the source rate)"
            )
        else:
            output_rate_description = "source timestamps preserved (no forced frame rate)"
        print(f" - video frame rate: {output_rate_description}")
        if video_properties.bit_depth > 8:
            print(" - bit-depth conversion: source above 8-bit to 8-bit 4:2:0 for HEVC encoding")
            print("   hardware: RGA scale_rkrga -> nv12; software fallback: software format conversion")
        print(f" - encoder QP: {args.qp}; tier: {args.tier}; level: {args.level}")
        mux_description = "skipped (--skip-mux)" if args.skip_mux else "enabled"
        print(f" - final mux: {mux_description}; force encoding: {str(args.force_encode).lower()}")
        if args.custom_offset != 0:
            offset_value = f"{args.custom_offset:+g} s"
            if args.offset_after_ms is None:
                offset_scope = "all segments"
            else:
                offset_scope = (
                    "segments starting at or after "
                    f"{format_clock_timestamp(args.offset_after_ms)}"
                )
            print(f" - custom offset: {offset_value} ({offset_scope})")
        print(f" - output folder: {processing_dir}\n")

        create_remux_helper(output_dir)

        encoded_count = 0
        skipped_count = 0
        active_hardware_decode = initial_hardware_decode
        with tempfile.NamedTemporaryFile(
            mode="w+", prefix=".ffmpeg-log.", dir=output_dir, encoding="utf-8", delete=False
        ) as log_handle:
            ffmpeg_log_path = Path(log_handle.name)
        try:
            for index, segment in enumerate(segments):
                segment_number = index + 1
                output_name = expected_output_names[index]
                output_path = output_dir / output_name
                if not args.force_encode and output_path.is_file():
                    skipped_count += 1
                    relative_output = output_path.relative_to(processing_dir)
                    print(f"[{segment_number}/{segment_count}] Skipping existing segment: {relative_output}\n")
                    continue

                apply_offset = (
                    args.offset_after_ms is None
                    or segment.start_milliseconds >= args.offset_after_ms
                )
                applied_offset = args.custom_offset if apply_offset else 0.0
                effective_start = segment.start_seconds + applied_offset
                effective_end = segment.end_seconds + applied_offset
                if effective_start < 0 or effective_end <= effective_start:
                    raise ScriptError(
                        f"Custom offset makes output segment #{segment_number} invalid: "
                        f"start={effective_start:.6f} end={effective_end:.6f}"
                    )

                _, trim_start, trim_end, seek_time = make_encode_command(
                    ffmpeg=ffmpeg,
                    source_video=source_video,
                    output_path=output_path,
                    segment=segment,
                    container_start=container_start,
                    applied_offset=applied_offset,
                    edge_trim=args.edge_trim,
                    seek_back=args.seek_back,
                    qp=args.qp,
                    tier=args.tier,
                    level=args.level,
                    hardware_decode=active_hardware_decode,
                    convert_to_8bit=video_properties.bit_depth > 8,
                    interlaced=is_interlaced,
                    source_frame_rate=source_frame_rate,
                    force_overwrite=args.force_encode,
                )
                merge_note = (
                    f" (combined from {segment.source_count} consecutive validated scenes)"
                    if segment.source_count > 1 else ""
                )
                print(
                    f"[{segment_number}/{segment_count}] Encoding segment "
                    f"{segment.start_text} - {segment.end_text}{merge_note}"
                )
                print(f"       Effective bounds: start={trim_start:.6f} end={trim_end:.6f}; seek={seek_time:.3f}")
                if applied_offset != 0:
                    print(f"       Custom offset applied: {applied_offset:g} s")

                def run_attempt(hardware_decode: bool) -> tuple[int, str | None]:
                    command, _, _, _ = make_encode_command(
                        ffmpeg=ffmpeg,
                        source_video=source_video,
                        output_path=output_path,
                        segment=segment,
                        container_start=container_start,
                        applied_offset=applied_offset,
                        edge_trim=args.edge_trim,
                        seek_back=args.seek_back,
                        qp=args.qp,
                        tier=args.tier,
                        level=args.level,
                        hardware_decode=hardware_decode,
                        convert_to_8bit=video_properties.bit_depth > 8,
                        interlaced=is_interlaced,
                        source_frame_rate=source_frame_rate,
                        force_overwrite=args.force_encode,
                    )
                    try:
                        with ffmpeg_log_path.open("w", encoding="utf-8", errors="replace") as log_file:
                            completed = subprocess.run(
                                command, check=False, stdout=subprocess.DEVNULL, stderr=log_file,
                                text=True, encoding="utf-8", errors="replace",
                            )
                    except OSError as exc:
                        raise ScriptError(f"Could not run FFmpeg: {exc}") from exc
                    if completed.returncode == 0 and output_path.is_file() and output_path.stat().st_size > 0:
                        return 0, None
                    status = completed.returncode if completed.returncode != 0 else 1
                    return status, ffmpeg_log_path.read_text(encoding="utf-8", errors="replace")

                status, log_text = run_attempt(active_hardware_decode)
                actual_hardware_decode = active_hardware_decode
                if status != 0 and args.decode_mode == "auto" and active_hardware_decode:
                    print(
                        "       [Warning] Automatic Rockchip MPP decoding failed; "
                        "retrying this segment with software decoding."
                    )
                    clean_partial_output(output_path)
                    status, log_text = run_attempt(False)
                    actual_hardware_decode = False
                    if status == 0:
                        active_hardware_decode = False
                if status != 0:
                    clean_partial_output(output_path)
                    if log_text:
                        print(log_text.rstrip(), file=sys.stderr)
                    raise ScriptError(
                        f"FFmpeg failed while encoding segment '{output_name}' "
                        f"({segment.start_text} - {segment.end_text}), exit code {status}."
                    )
                encoded_count += 1
                relative_output = output_path.relative_to(processing_dir)
                if not actual_hardware_decode and args.decode_mode == "auto" and initial_hardware_decode:
                    print(
                        f"       Finished and saved to: {relative_output} "
                        "(software decode fallback; hardware HEVC encoding)\n"
                    )
                else:
                    print(f"       Finished and saved to: {relative_output}\n")
        finally:
            ffmpeg_log_path.unlink(missing_ok=True)

        print(
            f"Segment summary: {encoded_count} encoded, {skipped_count} skipped, {segment_count} total "
            f"encoded segments from {listed_segment_count} validated scene images."
        )

        if args.skip_mux:
            print("\n[Mux] Skipped (--skip-mux was specified).")
            print()
        else:
            # In normal encoding mode, reject stale/missing files against the current scene list.
            mux_segments = sort_and_validate_encoded_segments(output_dir, segments)
            if encoded_count == 0 and complete_output.is_file():
                print(
                    "\n[Mux] Skipped: no segments needed encoding; "
                    "existing 'output_video.mkv' was preserved."
                )
                print()
            else:
                mux_encoded_segments(
                    ffmpeg, processing_dir, output_dir, complete_output, mux_segments
                )

        print(f"Total runtime: {format_runtime(started)} (hh:mm:ss)")
        return 0

    except ScriptError as exc:
        return fail(str(exc), started)
    except KeyboardInterrupt:
        print("[Error] Interrupted by user.", file=sys.stderr)
        print(f"Total runtime until interruption: {format_runtime(started)} (hh:mm:ss)", file=sys.stderr)
        return 130
    except OSError as exc:
        return fail(str(exc), started)


if __name__ == "__main__":
    raise SystemExit(main())
